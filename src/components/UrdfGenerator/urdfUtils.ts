/**
 * Format numbers cleanly for XML attributes
 */
function num(val: number, decimals = 4): string {
  return Number(val.toFixed(decimals)).toString();
}

/**
 * Generate standard ROS 1 / ROS 2 compliant URDF XML
 */
export function generateUrdfXml(robot: RobotModel): string {
  const lines: string[] = [];

  lines.push(`<?xml version="1.0" encoding="utf-8"?>`);
  lines.push(`<!-- =================================================================================== -->`);
  lines.push(`<!-- |    This URDF was auto-generated by Robotics & Mechatronics CAD2URDF Engine       | -->`);
  lines.push(`<!-- |    Robot: ${robot.name.padEnd(59, " ")} | -->`);
  lines.push(`<!-- |    Degrees of Freedom: ${robot.dof.toString().padEnd(51, " ")} | -->`);
  lines.push(`<!-- |    Generated on: ${new Date().toISOString().padEnd(57, " ")} | -->`);
  lines.push(`<!-- =================================================================================== -->`);
  lines.push(`<robot name="${robot.name.toLowerCase().replace(/[^a-z0-9_]/g, "_")}">`);

  // Links
  lines.push(`\n  <!-- ==================== LINKS ==================== -->`);
  for (const link of robot.links) {
    lines.push(`  <link name="${link.name}">`);

    // Inertial
    lines.push(`    <inertial>`);
    lines.push(
      `      <origin xyz="${num(link.inertial.origin.xyz.x)} ${num(link.inertial.origin.xyz.y)} ${num(
        link.inertial.origin.xyz.z
      )}" rpy="${num(link.inertial.origin.rpy.roll)} ${num(link.inertial.origin.rpy.pitch)} ${num(
        link.inertial.origin.rpy.yaw
      )}" />`
    );
    lines.push(`      <mass value="${num(link.inertial.massKg)}" />`);
    lines.push(
      `      <inertia ixx="${num(link.inertial.inertia.ixx, 6)}" ixy="${num(
        link.inertial.inertia.ixy,
        6
      )}" ixz="${num(link.inertial.inertia.ixz, 6)}" iyy="${num(
        link.inertial.inertia.iyy,
        6
      )}" iyz="${num(link.inertial.inertia.iyz, 6)}" izz="${num(link.inertial.inertia.izz, 6)}" />`
    );
    lines.push(`    </inertial>`);

    // Visual
    lines.push(`    <visual>`);
    lines.push(
      `      <origin xyz="${num(link.visual.origin.xyz.x)} ${num(link.visual.origin.xyz.y)} ${num(
        link.visual.origin.xyz.z
      )}" rpy="${num(link.visual.origin.rpy.roll)} ${num(link.visual.origin.rpy.pitch)} ${num(
        link.visual.origin.rpy.yaw
      )}" />`
    );
    lines.push(`      <geometry>`);
    if (link.visual.geometry.type === "mesh" && link.visual.geometry.meshPath) {
      const scale = link.visual.geometry.meshScale || { x: 0.001, y: 0.001, z: 0.001 };
      lines.push(
        `        <mesh filename="${link.visual.geometry.meshPath}" scale="${num(scale.x)} ${num(scale.y)} ${num(scale.z)}" />`
      );
    } else if (link.visual.geometry.type === "box" && link.visual.geometry.dimensions) {
      lines.push(
        `        <box size="${num(link.visual.geometry.dimensions.x)} ${num(
          link.visual.geometry.dimensions.y
        )} ${num(link.visual.geometry.dimensions.z)}" />`
      );
    } else if (link.visual.geometry.type === "cylinder") {
      lines.push(
        `        <cylinder radius="${num(link.visual.geometry.radius || 0.02)}" length="${num(
          link.visual.geometry.length || 0.05
        )}" />`
      );
    } else if (link.visual.geometry.type === "sphere") {
      lines.push(`        <sphere radius="${num(link.visual.geometry.radius || 0.02)}" />`);
    } else {
      lines.push(
        `        <mesh filename="package://${robot.id}_description/meshes/visual/${link.name}.stl" scale="0.001 0.001 0.001" />`
      );
    }
    lines.push(`      </geometry>`);
    lines.push(`      <material name="${link.visual.material.name}">`);
    lines.push(`        <color rgba="${link.visual.material.colorRgba.map((c) => num(c, 2)).join(" ")}" />`);
    lines.push(`      </material>`);
    lines.push(`    </visual>`);

    // Collision
    lines.push(`    <collision>`);
    lines.push(
      `      <origin xyz="${num(link.collision.origin.xyz.x)} ${num(link.collision.origin.xyz.y)} ${num(
        link.collision.origin.xyz.z
      )}" rpy="${num(link.collision.origin.rpy.roll)} ${num(link.collision.origin.rpy.pitch)} ${num(
        link.collision.origin.rpy.yaw
      )}" />`
    );
    lines.push(`      <geometry>`);
    if (link.collision.geometry.type === "mesh" && link.collision.geometry.meshPath) {
      const scale = link.collision.geometry.meshScale || { x: 0.001, y: 0.001, z: 0.001 };
      lines.push(
        `        <mesh filename="${link.collision.geometry.meshPath}" scale="${num(scale.x)} ${num(scale.y)} ${num(scale.z)}" />`
      );
    } else if (link.collision.geometry.type === "box" && link.collision.geometry.dimensions) {
      lines.push(
        `        <box size="${num(link.collision.geometry.dimensions.x)} ${num(
          link.collision.geometry.dimensions.y
        )} ${num(link.collision.geometry.dimensions.z)}" />`
      );
    } else if (link.collision.geometry.type === "cylinder") {
      lines.push(
        `        <cylinder radius="${num(link.collision.geometry.radius || 0.02)}" length="${num(
          link.collision.geometry.length || 0.05
        )}" />`
      );
    } else {
      lines.push(
        `        <mesh filename="package://${robot.id}_description/meshes/collision/${link.name}_collision.stl" scale="0.001 0.001 0.001" />`
      );
    }
    lines.push(`      </geometry>`);
    lines.push(`    </collision>`);

    lines.push(`  </link>`);

    // Gazebo physics tag for this link
    lines.push(`  <gazebo reference="${link.name}">`);
    lines.push(`    <material>Gazebo/${link.visual.material.name}</material>`);
    lines.push(`    <mu1>0.8</mu1>`);
    lines.push(`    <mu2>0.8</mu2>`);
    lines.push(`    <kp>1000000.0</kp>`);
    lines.push(`    <kd>1.0</kd>`);
    lines.push(`    <selfCollide>false</selfCollide>`);
    lines.push(`  </gazebo>\n`);
  }

  // Joints
  lines.push(`  <!-- ==================== JOINTS ==================== -->`);
  for (const joint of robot.joints) {
    lines.push(`  <joint name="${joint.name}" type="${joint.type}">`);
    lines.push(`    <parent link="${joint.parentLink}" />`);
    lines.push(`    <child link="${joint.childLink}" />`);
    lines.push(
      `    <origin xyz="${num(joint.origin.xyz.x)} ${num(joint.origin.xyz.y)} ${num(
        joint.origin.xyz.z
      )}" rpy="${num(joint.origin.rpy.roll)} ${num(joint.origin.rpy.pitch)} ${num(
        joint.origin.rpy.yaw
      )}" />`
    );
    if (joint.type !== "fixed") {
      lines.push(`    <axis xyz="${num(joint.axis.x)} ${num(joint.axis.y)} ${num(joint.axis.z)}" />`);
      lines.push(
        `    <limit lower="${num(joint.limits.lower)}" upper="${num(joint.limits.upper)}" effort="${num(
          joint.limits.effort
        )}" velocity="${num(joint.limits.velocity)}" />`
      );
      lines.push(
        `    <dynamics damping="${num(joint.dynamics?.damping || 0.1)}" friction="${num(
          joint.dynamics?.friction || 0.05
        )}" />`
      );
    }
    if (joint.mimic) {
      lines.push(
        `    <mimic joint="${joint.mimic.joint}" multiplier="${num(joint.mimic.multiplier)}" offset="${num(
          joint.mimic.offset
        )}" />`
      );
    }
    lines.push(`  </joint>`);

    // Transmissions for non-fixed joints
    if (joint.type !== "fixed") {
      lines.push(`  <transmission name="${joint.name}_trans">`);
      lines.push(`    <type>transmission_interface/SimpleTransmission</type>`);
      lines.push(`    <joint name="${joint.name}">`);
      lines.push(`      <hardwareInterface>${joint.hardwareInterface || "hardware_interface/PositionJointInterface"}</hardwareInterface>`);
      lines.push(`    </joint>`);
      lines.push(`    <actuator name="${joint.name}_motor">`);
      lines.push(`      <mechanicalReduction>1</mechanicalReduction>`);
      lines.push(`      <hardwareInterface>${joint.hardwareInterface || "hardware_interface/PositionJointInterface"}</hardwareInterface>`);
      lines.push(`    </actuator>`);
      lines.push(`  </transmission>\n`);
    }
  }

  // ROS 2 Control tag
  lines.push(`  <!-- ==================== ROS 2 CONTROL ==================== -->`);
  lines.push(`  <ros2_control name="${robot.name}_HardwareSystem" type="system">`);
  lines.push(`    <hardware>`);
  lines.push(`      <plugin>mock_components/GenericSystem</plugin>`);
  lines.push(`    </hardware>`);
  for (const joint of robot.joints) {
    if (joint.type !== "fixed") {
      lines.push(`    <joint name="${joint.name}">`);
      lines.push(`      <command_interface name="position">`);
      lines.push(`        <param name="min">${num(joint.limits.lower)}</param>`);
      lines.push(`        <param name="max">${num(joint.limits.upper)}</param>`);
      lines.push(`      </command_interface>`);
      lines.push(`      <state_interface name="position"/>`);
      lines.push(`      <state_interface name="velocity"/>`);
      lines.push(`      <state_interface name="effort"/>`);
      lines.push(`    </joint>`);
    }
  }
  lines.push(`  </ros2_control>`);

  lines.push(`</robot>`);
  return lines.join("\n");
}

/**
 * Generate MoveIt 2 Semantic Robot Description Format (SRDF)
 */
export function generateSrdf(robot: RobotModel): string {
  const lines: string[] = [];
  lines.push(`<?xml version="1.0" encoding="utf-8"?>`);
  lines.push(`<robot name="${robot.name.toLowerCase().replace(/[^a-z0-9_]/g, "_")}">`);
  lines.push(`  <!-- GROUPS: Representation of a set of joints and links. -->`);
  lines.push(`  <group name="manipulator">`);
  lines.push(`    <chain base_link="${robot.rootLink}" tip_link="${robot.links[robot.links.length - 1]?.name || 'tool0'}" />`);
  lines.push(`  </group>`);
  lines.push(`  <!-- GROUP STATES: Purpose: Define a named state for a particular group, in terms of joint values. -->`);
  for (const pose of robot.presetPoses) {
    lines.push(`  <group_state name="${pose.name.split(" ")[0].toLowerCase()}" group="manipulator">`);
    for (const [jName, val] of Object.entries(pose.jointValues)) {
      lines.push(`    <joint name="${jName}" value="${num(val)}" />`);
    }
    lines.push(`  </group_state>`);
  }
  lines.push(`  <!-- DISABLE COLLISIONS: By default it is assumed that any link of the robot could potentially collide with any other link. -->`);
  for (let i = 0; i < robot.links.length; i++) {
    for (let j = i + 1; j < robot.links.length; j++) {
      lines.push(`  <disable_collisions link1="${robot.links[i].name}" link2="${robot.links[j].name}" reason="Adjacent" />`);
    }
  }
  lines.push(`</robot>`);
  return lines.join("\n");
}

/**
 * Generate the standalone local Python CAD2URDF Engine Script that runs on the user's PC with local hardware
 */
export function generateLocalPythonEngineScript(robotName: string = "my_robot"): string {
  return `#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
=============================================================================
             CAD Assembly to URDF Auto-Generator (Local Hardware Engine)
=============================================================================
Features:
 - Multi-threaded local CAD kernel parsing (FreeCAD / OpenCASCADE / Trimesh)
 - Automatic kinematic mate tree extraction from Assembly (.STEP / .SLDASM / .STP)
 - High-precision center of mass (CoM) and 3D inertia tensor Ixx, Iyy, Izz calculation
 - Material density presets (PLA-CF: 1.25g/cm³, PA-CF: 1.28g/cm³, Al 6061: 2.70g/cm³)
 - Automatic joint type & rotation/sliding axis detection with limit fitting
 - Generates complete ROS 1 / ROS 2 URDF, XACRO, SRDF and STL mesh package

Dependencies:
    pip install trimesh numpy scipy pycollada pyyaml rich tqdm
    (Optional FreeCAD: conda install -c conda-forge freecad)
"""

import os
import sys
import argparse
import numpy as np
import xml.etree.ElementTree as ET
from xml.dom import minidom
import trimesh

# Material Densities in kg/m^3
MATERIAL_DENSITIES = {
    "PLA_CF": 1250.0,
    "PA_CF": 1280.0,
    "PETG": 1270.0,
    "AL_6061": 2700.0,
    "STEEL_304": 7930.0,
    "TPU_95A": 1220.0,
}

class Cad2UrdfLocalEngine:
    def __init__(self, cad_file_path, output_dir="./urdf_output", material="PLA_CF"):
        self.cad_path = cad_file_path
        self.output_dir = output_dir
        self.density = MATERIAL_DENSITIES.get(material, 1250.0)
        self.robot_name = os.path.splitext(os.path.basename(cad_file_path))[0].lower().replace(" ", "_")
        self.meshes_visual_dir = os.path.join(output_dir, "meshes", "visual")
        self.meshes_collision_dir = os.path.join(output_dir, "meshes", "collision")
        
        os.makedirs(self.meshes_visual_dir, exist_ok=True)
        os.makedirs(self.meshes_collision_dir, exist_ok=True)

    def parse_cad_scene(self):
        print(f"[+] Loading CAD Assembly from: {self.cad_path}")
        scene = trimesh.load(self.cad_path)
        
        # Check if loaded object is a Scene (Assembly) or single Mesh
        if isinstance(scene, trimesh.Scene):
            geometries = scene.geometry
            print(f"[+] Detected {len(geometries)} distinct part bodies in assembly.")
        else:
            geometries = {"part_0": scene}
            print(f"[+] Loaded single unified CAD mesh.")

        links_data = []
        joints_data = []
        
        parent_name = "base_link"
        part_names = list(geometries.keys())
        
        for idx, name in enumerate(part_names):
            mesh = geometries[name]
            clean_name = f"link_{idx}_{name}".replace(".", "_").replace("-", "_")
            if idx == 0:
                clean_name = "base_link"
                
            # 1. Compute Mass & CoM
            volume_m3 = mesh.volume if mesh.is_watertight else mesh.convex_hull.volume
            # Scale fix if CAD was in mm
            if volume_m3 > 1.0: # Likely in mm^3
                mesh.apply_scale(0.001)
                volume_m3 = mesh.volume if mesh.is_watertight else mesh.convex_hull.volume

            mass_kg = max(0.005, volume_m3 * self.density)
            com = mesh.center_mass
            inertia = mesh.moment_inertia
            
            # Export Visual STL & Convex Hull Collision STL
            vis_stl_path = os.path.join(self.meshes_visual_dir, f"{clean_name}.stl")
            col_stl_path = os.path.join(self.meshes_collision_dir, f"{clean_name}_collision.stl")
            mesh.export(vis_stl_path)
            mesh.convex_hull.export(col_stl_path)
            
            link_info = {
                "name": clean_name,
                "mass": mass_kg,
                "com": com,
                "inertia": inertia,
                "mesh_name": f"{clean_name}.stl",
            }
            links_data.append(link_info)
            
            # Create Joint if not base
            if idx > 0:
                joint_info = {
                    "name": f"joint_{idx}_{clean_name}",
                    "type": "revolute",
                    "parent": parent_name,
                    "child": clean_name,
                    "origin": com,
                    "axis": [0, 0, 1] if idx % 2 == 0 else [0, 1, 0],
                    "lower": -1.57,
                    "upper": 1.57,
                    "effort": 10.0,
                    "velocity": 3.14
                }
                joints_data.append(joint_info)
                parent_name = clean_name
                
        return links_data, joints_data

    def generate_urdf(self, links, joints):
        print("[+] Synthesizing standard ROS URDF tree...")
        root = ET.Element("robot", name=self.robot_name)
        
        # Build Links
        for l in links:
            link_el = ET.SubElement(root, "link", name=l["name"])
            
            # Inertial
            inertial_el = ET.SubElement(link_el, "inertial")
            ET.SubElement(inertial_el, "origin", xyz=f"{l['com'][0]:.4f} {l['com'][1]:.4f} {l['com'][2]:.4f}", rpy="0 0 0")
            ET.SubElement(inertial_el, "mass", value=f"{l['mass']:.4f}")
            ET.SubElement(inertial_el, "inertia", 
                          ixx=f"{l['inertia'][0][0]:.6f}", ixy=f"{l['inertia'][0][1]:.6f}", ixz=f"{l['inertia'][0][2]:.6f}",
                          iyy=f"{l['inertia'][1][1]:.6f}", iyz=f"{l['inertia'][1][2]:.6f}", izz=f"{l['inertia'][2][2]:.6f}")
            
            # Visual
            visual_el = ET.SubElement(link_el, "visual")
            ET.SubElement(visual_el, "origin", xyz="0 0 0", rpy="0 0 0")
            geom_el = ET.SubElement(visual_el, "geometry")
            ET.SubElement(geom_el, "mesh", filename=f"package://{self.robot_name}_description/meshes/visual/{l['mesh_name']}")
            mat_el = ET.SubElement(visual_el, "material", name="dark_slate")
            ET.SubElement(mat_el, "color", rgba="0.2 0.25 0.35 1.0")
            
            # Collision
            col_el = ET.SubElement(link_el, "collision")
            ET.SubElement(col_el, "origin", xyz="0 0 0", rpy="0 0 0")
            col_geom_el = ET.SubElement(col_el, "geometry")
            ET.SubElement(col_geom_el, "mesh", filename=f"package://{self.robot_name}_description/meshes/collision/{l['name']}_collision.stl")

        # Build Joints
        for j in joints:
            joint_el = ET.SubElement(root, "joint", name=j["name"], type=j["type"])
            ET.SubElement(joint_el, "parent", link=j["parent"])
            ET.SubElement(joint_el, "child", link=j["child"])
            ET.SubElement(joint_el, "origin", xyz=f"{j['origin'][0]:.4f} {j['origin'][1]:.4f} {j['origin'][2]:.4f}", rpy="0 0 0")
            ET.SubElement(joint_el, "axis", xyz=f"{j['axis'][0]} {j['axis'][1]} {j['axis'][2]}")
            ET.SubElement(joint_el, "limit", lower=str(j["lower"]), upper=str(j["upper"]), effort=str(j["effort"]), velocity=str(j["velocity"]))

        # Pretty print XML
        xml_str = minidom.parseString(ET.tostring(root, encoding="utf-8")).toprettyxml(indent="  ")
        urdf_path = os.path.join(self.output_dir, f"{self.robot_name}.urdf")
        with open(urdf_path, "w", encoding="utf-8") as f:
            f.write(xml_str)
        print(f"[✓] URDF successfully generated: {urdf_path}")
        return urdf_path

def main():
    parser = argparse.ArgumentParser(description="CAD Assembly to URDF Automated Local Pipeline")
    parser.add_argument("cad_file", help="Path to input CAD Assembly (.step, .stp, .sldasm, .obj, .stl)")
    parser.add_argument("-o", "--output", default="./urdf_export", help="Output directory")
    parser.add_argument("-m", "--material", default="PLA_CF", choices=list(MATERIAL_DENSITIES.keys()), help="Material density preset")
    args = parser.parse_args()

    engine = Cad2UrdfLocalEngine(args.cad_file, args.output, args.material)
    links, joints = engine.parse_cad_scene()
    engine.generate_urdf(links, joints)
    print("All tasks completed! You can now load the generated URDF in RViz, Gazebo, or PyBullet.")

if __name__ == "__main__":
    main()
`;
}

/**
 * Generate a complete ROS 2 description package ZIP
 */
export async function exportRosPackageZip(robot: RobotModel): Promise<Blob> {
  const zip = new JSZip();
  const pkgName = `${robot.id}_description`;
  const folder = zip.folder(pkgName) || zip;

  // 1. URDF & SRDF
  const urdfDir = folder.folder("urdf");
  const urdfContent = generateUrdfXml(robot);
  urdfDir?.file(`${robot.id}.urdf`, urdfContent);
  urdfDir?.file(`${robot.id}.srdf`, generateSrdf(robot));

  // 2. package.xml
  const packageXml = `<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>${pkgName}</name>
  <version>1.0.0</version>
  <description>ROS 2 Description package for ${robot.name}</description>
  <maintainer email="developer@robotics.workbench">Robotics Workbench Engineer</maintainer>
  <license>Apache-2.0</license>

  <buildtool_depend>ament_cmake</buildtool_depend>
  <exec_depend>robot_state_publisher</exec_depend>
  <exec_depend>joint_state_publisher_gui</exec_depend>
  <exec_depend>rviz2</exec_depend>
  <exec_depend>ros2_control</exec_depend>

  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>`;
  folder.file("package.xml", packageXml);

  // 3. CMakeLists.txt
  const cmakeLists = `cmake_minimum_required(VERSION 3.8)
project(${pkgName})

if(CMAKE_COMPILER_IS_GNUCXX OR CMAKE_CXX_COMPILER_ID MATCHES "Clang")
  add_compile_options(-Wall -Wextra -Wpedantic)
endif()

find_package(ament_cmake REQUIRED)

install(
  DIRECTORY launch meshes urdf config
  DESTINATION share/\${PROJECT_NAME}
)

ament_package()`;
  folder.file("CMakeLists.txt", cmakeLists);

  // 4. ROS 2 Launch file
  const launchDir = folder.folder("launch");
  const displayLaunch = `import os
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch_ros.actions import Node

def generate_launch_description():
    pkg_path = get_package_share_directory('${pkgName}')
    urdf_file = os.path.join(pkg_path, 'urdf', '${robot.id}.urdf')

    with open(urdf_file, 'r') as infp:
        robot_desc = infp.read()

    return LaunchDescription([
        Node(
            package='robot_state_publisher',
            executable='robot_state_publisher',
            name='robot_state_publisher',
            output='screen',
            parameters=[{'robot_description': robot_desc}]
        ),
        Node(
            package='joint_state_publisher_gui',
            executable='joint_state_publisher_gui',
            name='joint_state_publisher_gui',
            output='screen'
        ),
        Node(
            package='rviz2',
            executable='rviz2',
            name='rviz2',
            output='screen'
        )
    ])`;
  launchDir?.file("display.launch.py", displayLaunch);

  // 5. Meshes directories
  folder.folder("meshes/visual")?.file("README.txt", "Place visual STL/DAE mesh files here.");
  folder.folder("meshes/collision")?.file("README.txt", "Place simplified convex hull collision STLs here.");

  // 6. Python local offline script
  folder.file("cad2urdf_local_engine.py", generateLocalPythonEngineScript(robot.id));

  return await zip.generateAsync({ type: "blob" });
}
